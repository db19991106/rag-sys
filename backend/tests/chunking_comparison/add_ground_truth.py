def add_ground_truth(test_cases_path: str):
    """为测试用例添加真值答案"""
    with open(test_cases_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    updated_count = 0
    for case in data['test_cases']:
        case_id = case.get('id', '')
        if case_id in GROUND_TRUTH_ANSWERS:
            case['ground_truth_answer'] = GROUND_TRUTH_ANSWERS[case_id]
            updated_count += 1
        else:
            # 为没有预定义答案的问题生成通用答案
            case['ground_truth_answer'] = f"请参考文档中关于'{case['query']}'的相关内容。"

    with open(test_cases_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"已为 {updated_count}/{len(data['test_cases'])} 个测试用例添加真值答案")
    return data


